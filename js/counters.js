// Đáp án nhiễu cho câu "đọc số đếm": đổi âm đầu của trợ số từ (h/b/p, k/g, s/z) và phần số (いち/いっ, ろく/ろっ…)
const VOICE = { は: 'ばぱ', ひ: 'びぴ', ふ: 'ぶぷ', へ: 'べぺ', ほ: 'ぼぽ', か: 'が', き: 'ぎ', く: 'ぐ', け: 'げ', こ: 'ご', さ: 'ざ', し: 'じ', す: 'ず', せ: 'ぜ', そ: 'ぞ', た: 'だ', ち: 'ぢ', つ: 'づ', て: 'で', と: 'ど' };
const BASE = {}; for (const [k, v] of Object.entries(VOICE)) for (const c of v) BASE[c] = k;
const NUM_R = { 1: ['いち', 'いっ'], 2: ['に'], 3: ['さん'], 4: ['よん', 'よ', 'し'], 5: ['ご'], 6: ['ろく', 'ろっ'], 7: ['なな', 'しち'], 8: ['はち', 'はっ'], 9: ['きゅう', 'く'], 10: ['じゅう', 'じゅっ'] };
export function countWrong(cn, n) {
  const C = COUNTERS[cn], right = C.r[n - 1];
  const ok = new Set(accepted(cn, n));
  const out = new Set();
  if (cn === 'つ' || cn === '人') out.add(NUM_R[n][0] + (cn === 'つ' ? 'つ' : 'にん'));
  else {
    const pre = NUM_R[n].find(p => right.startsWith(p)) || '';
    const rest = right.slice(pre.length);
    const base = BASE[rest[0]] || rest[0];
    for (const p of NUM_R[n]) for (const v of [base, ...(VOICE[base] || '')]) out.add(p + v + rest.slice(1));
  }
  // thiếu thì lấy cách đọc của số bên cạnh (đọc nhầm số)
  for (const k of [n + 1, n - 1, n + 2, n - 2]) if (k >= 1 && k <= 10) out.add(C.r[k - 1]);
  for (const x of ok) out.delete(x);
  return [...out];
}

